//! Build the 1.8.9 block movement-material table from a `BlockMaterialProbe18` dump.
//!
//! `World.getTopPosition` (chunk-generation mob packs) scans down while the
//! block below does not block movement, and also skips `Material.FOILAGE`:
//! 1.8's `Material.blocksMovement` is false for air, fluids, plants and every
//! block without a collision-material, which is not the modern opacity rule
//! (glass and snow layers block movement but have no opacity; water and
//! leaves have opacity but do not stop the scan the same way). The dump this
//! reads is produced by `tools/BlockMaterialProbe18.java` on the real 1.8.9
//! jar:
//!
//! ```text
//! blockId <tab> class <tab> blocksMovement <tab> foliage
//! ```
//!
//! The output table is keyed by the engine's flattened block names: every
//! 1.8 state's `legacy_1_8_9::block_state` name inherits its block's
//! material, so all variants of one 1.8 block share one row.
//!
//! ```sh
//! javac -cp <1.8.9 named jar + libraries> tools/BlockMaterialProbe18.java
//! java -cp <1.8.9 named jar + libraries>:. BlockMaterialProbe18 > block-materials-1.8.9.txt
//! cargo run -p horizon-client --example prepare_1_8_9_block_materials -- \
//!     --dump block-materials-1.8.9.txt \
//!     --out crates/horizon-world/src/block_materials_1_8_9.rs
//! ```
use horizon_world::legacy_1_8_9::{MAX_BLOCK_ID, block_state};
use std::{
    collections::{BTreeSet, HashMap},
    error::Error,
    fs,
    path::PathBuf,
};

fn main() -> Result<(), Box<dyn Error>> {
    let mut dump = PathBuf::new();
    let mut out = PathBuf::from("crates/horizon-world/src/block_materials_1_8_9.rs");
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--dump" => dump = args.next().ok_or("--dump needs a path")?.into(),
            "--out" => out = args.next().ok_or("--out needs a path")?.into(),
            other => return Err(format!("unknown argument {other}").into()),
        }
    }
    if dump.as_os_str().is_empty() {
        return Err("--dump needs the BlockMaterialProbe18 dump".into());
    }
    let text = fs::read_to_string(&dump)?;
    let mut rows: HashMap<u16, (bool, bool)> = HashMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let mut fields = line.split('\t');
        let id: u16 = fields.next().ok_or("row has no id")?.parse()?;
        let _class = fields.next().ok_or("row has no class")?;
        let blocks = fields.next().ok_or("row has no blocksMovement")? == "true";
        let foliage = fields.next().ok_or("row has no foliage")? == "true";
        if id <= MAX_BLOCK_ID {
            rows.insert(id, (blocks, foliage));
        }
    }
    let mut non_blocking = BTreeSet::new();
    let mut foliage = BTreeSet::new();
    let mut missing = Vec::new();
    let potted: Vec<&str> = horizon_world::legacy_1_8_9::POTTED_CONTENTS
        .iter()
        .map(|&(_, _, name)| name)
        .collect();
    // 1.8 keeps a skull's type and a flower pot's contents in the tile
    // entity, so the context-free state projection names only the default
    // variants. Every one of the block's states shares the same material.
    const SKULLS: [&str; 12] = [
        "minecraft:creeper_head",
        "minecraft:creeper_wall_head",
        "minecraft:dragon_head",
        "minecraft:dragon_wall_head",
        "minecraft:player_head",
        "minecraft:player_wall_head",
        "minecraft:skeleton_skull",
        "minecraft:skeleton_wall_skull",
        "minecraft:wither_skeleton_skull",
        "minecraft:wither_skeleton_wall_skull",
        "minecraft:zombie_head",
        "minecraft:zombie_wall_head",
    ];
    for id in 0..=MAX_BLOCK_ID {
        let Some(&(blocks, leaf)) = rows.get(&id) else {
            missing.push(id);
            continue;
        };
        let family: &[&str] = match id {
            140 => &potted,
            144 => &SKULLS,
            _ => &[],
        };
        for name in family {
            if !blocks {
                non_blocking.insert((*name).to_owned());
            }
            if leaf {
                foliage.insert((*name).to_owned());
            }
        }
        for meta in 0..16 {
            let state = block_state(id, meta);
            let name = state.name;
            if !blocks {
                non_blocking.insert(name.clone());
            }
            if leaf {
                foliage.insert(name);
            }
        }
    }
    if !missing.is_empty() {
        return Err(format!("dump has no row for block ids {missing:?}").into());
    }
    let mut body = String::new();
    body.push_str(
        "//! Generated by `cargo run -p horizon-client --example prepare_1_8_9_block_materials`.\n\
         //!\n\
         //! 1.8's `Material.blocksMovement` and `Material.FOILAGE` per flattened\n\
         //! block name, as `World.getTopPosition` reads them. Do not edit: rerun\n\
         //! the generator instead.\n\n",
    );
    body.push_str(
        "/// Blocks whose 1.8 material does not block movement: air, fluids, plants,\n\
         /// torches, rails, redstone, snow layers, carpets, flower pots, skulls...\n\
         pub const NON_BLOCKING: &[&str] = &[\n",
    );
    for name in &non_blocking {
        body.push_str(&format!("    {name:?},\n"));
    }
    body.push_str("];\n\n");
    body.push_str("/// Blocks whose 1.8 material is `Material.FOILAGE` (the leaves).\n");
    body.push_str("pub const FOLIAGE: &[&str] = &[\n");
    for name in &foliage {
        body.push_str(&format!("    {name:?},\n"));
    }
    body.push_str("];\n\n");
    body.push_str(
        "/// `Material.blocksMovement` for a flattened block name.\n\
         pub fn blocks_movement(block: &str) -> bool {\n\
         \x20   NON_BLOCKING.binary_search(&block).is_err()\n\
         }\n\n\
         /// `block.getMaterial() == Material.FOILAGE`.\n\
         pub fn is_foliage(block: &str) -> bool {\n\
         \x20   FOLIAGE.binary_search(&block).is_ok()\n\
         }\n",
    );
    fs::write(&out, body)?;
    println!(
        "{} non-blocking, {} foliage blocks -> {}",
        non_blocking.len(),
        foliage.len(),
        out.display()
    );
    Ok(())
}
