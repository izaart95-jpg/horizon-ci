//! Build the 1.8.9 item-name table a prepared 1.8.9 root filters `items.json` to.
//!
//! A 26.3 resource root's `items.json` names every item of 26.3 (1,658 of
//! them), and the flattened 1.8.9 root keeps the whole file so the default
//! components stay 26.3-shaped for now. Only the items 1.8.9 had may be
//! reachable, though: [`legacy_id`] says which names a 1.8 numeric id reaches,
//! and splash potion is the one 1.8 item the datafixer only names when a
//! stack carries its damage bit, so the reverse map lacks it.
//!
//! The output is the sorted name list `horizon_world::items_1_8_9` filters
//! with, and it is regenerated whenever the prepared root's `items.json`
//! changes:
//!
//! ```sh
//! cargo run -p horizon-items --example prepare_1_8_9_item_names -- \
//!     --root .local/horizon-client/1.8.9 \
//!     --out crates/horizon-world/src/items_1_8_9.rs \
//!     --filter-items
//! ```
//!
//! `--filter-items` also rewrites the root's `items.json` down to those names
//! (content mods' names outside `minecraft:` stay), so the engine bundle does
//! not ship the 26.3 rows the runtime filter would drop anyway.
use horizon_items::legacy_1_8_9::legacy_id;
use serde_json::Value;
use std::{collections::BTreeSet, error::Error, fs, path::PathBuf};

fn main() -> Result<(), Box<dyn Error>> {
    let mut root = PathBuf::from(".local/horizon-client/1.8.9");
    let mut out = PathBuf::from("crates/horizon-world/src/items_1_8_9.rs");
    let mut filter_items = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--root" => root = args.next().ok_or("--root needs a path")?.into(),
            "--out" => out = args.next().ok_or("--out needs a path")?.into(),
            "--filter-items" => filter_items = true,
            other => return Err(format!("unknown argument {other}").into()),
        }
    }
    let raw: Value = serde_json::from_slice(&fs::read(root.join("items.json"))?)?;
    let items = raw.as_object().ok_or("items.json is not an object")?;
    let names: BTreeSet<&str> = items
        .keys()
        .map(String::as_str)
        .filter(|name| legacy_id(name).is_some() || *name == "minecraft:splash_potion")
        .collect();
    if filter_items {
        let before = items.len();
        let kept: serde_json::Map<String, Value> = items
            .iter()
            .filter(|(name, _)| !name.starts_with("minecraft:") || names.contains(name.as_str()))
            .map(|(name, components)| (name.clone(), components.clone()))
            .collect();
        let mut text = serde_json::to_string_pretty(&kept)?;
        text.push('\n');
        fs::write(root.join("items.json"), text)?;
        println!(
            "items.json: {before} -> {} entries ({} kept, {} content mods)",
            kept.len(),
            names.len(),
            kept.len() - names.len()
        );
    }
    let mut body = String::new();
    body.push_str(
        "//! Generated by `cargo run -p horizon-items --example prepare_1_8_9_item_names`.\n\
         //!\n\
         //! The items 1.8.9 registered, as the current flattened names a 1.8\n\
         //! numeric id reaches. `item_defaults::read` drops every other\n\
         //! `minecraft:` item of the prepared root's 26.3-shaped `items.json`\n\
         //! on a 1.8 target, so commands, the creative menu and recipes cannot\n\
         //! reach an item 1.8 never had. Do not edit: rerun the generator\n\
         //! instead.\n\n",
    );
    body.push_str(&format!(
        "/// The 1.8.9 item names, sorted for `binary_search` ({} items).\n\
         pub const ITEMS: &[&str] = &[\n",
        names.len()
    ));
    for name in &names {
        body.push_str(&format!("    {name:?},\n"));
    }
    body.push_str("];\n\n");
    body.push_str(
        "/// Whether 1.8.9 has an item by this flattened name.\n\
         pub fn has_item(name: &str) -> bool {\n\
         \x20   ITEMS.binary_search(&name).is_ok()\n\
         }\n",
    );
    fs::write(&out, body)?;
    println!("{} items -> {}", names.len(), out.display());
    Ok(())
}
