#!/usr/bin/env python3
"""Build the 1.8.9 enchantment tables from an `EnchantProbe18` dump.

1.8's `EnchantmentHelper.buildEnchantmentList` picks from
`Enchantment.enchantmentsList` by each entry's weight, its
`getMinEnchantability`/`getMaxEnchantability` window at every level, and
`canApplyTogether`; the item side is `Item.b()` (enchantability) and
`Enchantment.canApply`. None of that survives in the 26.3 data: the weights,
the cost windows and the incompatibilities all moved to
`data/minecraft/enchantment/*.json`, and the item types are component tags
rather than an `EnumEnchantmentType`.

The dump `tools/EnchantProbe18.java` writes on the real 1.8.9 server jar is:

    E <id> <name> <weight> <min level> <max level> <type ordinal> <first1>..<first5> <last1>..<last5> <compatible ids>
    A <item> <mask>
    I <item> <enchantability> <type mask>
    T <item> <level> <seed> <id:level,...> <nextInt(1000)>

The `A` mask's bit `n` is `Enchantment.isAcceptableItem` (yarn's name for
the 1.8 `canApply(ItemStack)`) for the `n`-th enchantment in ascending id
order: the anvil's combine gate. Its overrides make an axe take the damage
enchantments and shears take efficiency, silk touch and unbreaking, which the
type mask refuses. `buildEnchantmentList` itself gates on the enchantment's
`EnumEnchantmentType` against the `I` line's type mask, which is what
`can_apply` uses (a book bypasses the gate, as the jar does). The `T` lines
pin the whole draw sequence: the seed, the picked levels and the
`nextInt(1000)` after the build prove how many draws it made.

    javac -cp .local/minecraft/1.8.9/server.jar -d /tmp/ench18 tools/EnchantProbe18.java
    java -cp .local/minecraft/1.8.9/server.jar:/tmp/ench18 EnchantProbe18 \
        > .local/minecraft/1.8.9/enchant-1.8.9.txt
    python3 tools/prepare_1_8_9_enchant.py \
        --dump .local/minecraft/1.8.9/enchant-1.8.9.txt \
        --out crates/horizon-items/src/enchant_1_8_9_tables.rs
"""
import argparse
import pathlib

HEADER = """\
// 1.8.9's enchantment tables, generated by
// `tools/prepare_1_8_9_enchant.py` from a `tools/EnchantProbe18.java` dump of
// the real 1.8.9 server jar.
//
// Do not edit by hand: rerun the probe and the exporter.
// (Plain comments: this file is `include!`d, where inner doc comments are
// not allowed.)
"""

STRUCT = """
/// `Enchantment` in 1.8.9: its id, weight, cost window at every level and
/// what it can be combined with.
pub struct Enchantment18 {
    /// `Enchantment.enchantmentId`.
    pub id: u32,
    pub name: &'static str,
    /// `EnumEnchantmentType.ordinal()`: `buildEnchantmentList` only offers an
    /// enchantment to an item the type accepts.
    pub kind: u8,
    /// `Enchantment.getWeight`.
    pub weight: u32,
    /// `Enchantment.getMaxLevel`.
    pub max_level: u32,
    /// `Enchantment.getMinEnchantability(level)` for levels 1 to 5.
    pub first: [i32; 5],
    /// `Enchantment.getMaxEnchantability(level)` for levels 1 to 5.
    pub last: [i32; 5],
    /// Bit `n` set when `canApplyTogether` accepts the `n`-th entry of
    /// `ENCHANTMENTS`.
    pub compatible: u32,
}
"""


def rust_array(values: list[int]) -> str:
    return "[" + ", ".join(str(v) for v in values) + "]"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dump", required=True, type=pathlib.Path)
    parser.add_argument(
        "--out",
        default=pathlib.Path("crates/horizon-items/src/enchant_1_8_9_tables.rs"),
        type=pathlib.Path,
    )
    args = parser.parse_args()

    enchantments: list[dict] = []
    items: list[tuple[str, int, int]] = []
    accepts: dict[str, int] = {}
    vectors: list[tuple] = []
    for line in args.dump.read_text().splitlines():
        kind, _, rest = line.partition(" ")
        if kind == "E":
            f = rest.split(" ")
            enchantments.append(
                {
                    "id": int(f[0]),
                    "name": f[1],
                    "weight": int(f[2]),
                    "max_level": int(f[4]),
                    "kind": int(f[5]),
                    "first": [int(v) for v in f[6:11]],
                    "last": [int(v) for v in f[11:16]],
                    "compatible": [int(v) for v in f[16:]],
                }
            )
        elif kind == "A":
            name, mask = rest.split(" ")
            accepts[name] = int(mask)
        elif kind == "I":
            name, enchantability, types = rest.split(" ")
            items.append((name, int(enchantability), int(types)))
        elif kind == "T":
            f = rest.split(" ")
            listing = (
                []
                if f[3] == "-"
                else [tuple(int(v) for v in pair.split(":")) for pair in f[3].split(",")]
            )
            vectors.append((f[0], int(f[1]), int(f[2]), listing, int(f[4])))

    if len(enchantments) != 25 or len(items) != 337 or len(accepts) != 337:
        raise SystemExit(
            f"unexpected dump: {len(enchantments)} enchantments, "
            f"{len(items)} items, {len(accepts)} accept rows"
        )
    missing = {name for name, _, _ in items} ^ set(accepts)
    if missing:
        raise SystemExit(f"items without a matching A row: {sorted(missing)}")
    order = {e["id"]: i for i, e in enumerate(enchantments)}

    out = [HEADER, STRUCT]
    out.append(
        "\n/// `Enchantment.enchantmentsList`, in ascending 1.8 id (the order\n"
        "/// `buildEnchantmentList` visits them in).\n"
        f"pub const ENCHANTMENTS: [Enchantment18; {len(enchantments)}] = [\n"
    )
    for e in enchantments:
        mask = 0
        for other in e["compatible"]:
            mask |= 1 << order[other]
        out.append(
            "    Enchantment18 {\n"
            f"        id: {e['id']},\n"
            f"        name: \"{e['name']}\",\n"
            f"        kind: {e['kind']},\n"
            f"        weight: {e['weight']},\n"
            f"        max_level: {e['max_level']},\n"
            f"        first: {rust_array(e['first'])},\n"
            f"        last: {rust_array(e['last'])},\n"
            f"        compatible: 0x{mask:08x},\n"
            "    },\n"
        )
    out.append("];\n")
    out.append(
        "\n/// 1.8's items in registry order: `Item.b()` (the enchantability\n"
        "/// `buildEnchantmentList` starts from), the `EnumEnchantmentType`\n"
        "/// mask from the probe's `I` line, and `Enchantment.isAcceptableItem`\n"
        "/// from its `A` line. In the type mask bit `n` is set when\n"
        "/// `EnchantmentType.values()[n]` accepts the item; `buildEnchantmentList`\n"
        "/// gates on the enchantment's type through it. In the accept mask bit\n"
        "/// `n` is set when the `n`-th entry of `ENCHANTMENTS` takes the item,\n"
        "/// overrides included: an axe takes the damage enchantments and shears\n"
        "/// take efficiency, silk touch and unbreaking, which the type mask\n"
        "/// refuses. A book takes every entry, which the caller adds.\n"
        f"pub const ITEMS: [(&str, u32, u32, u32); {len(items)}] = [\n"
    )
    for name, enchantability, types in items:
        out.append(
            f'    ("{name}", {enchantability}, 0x{types:08x}, '
            f'0x{accepts[name]:08x}),\n'
        )
    out.append("];\n")
    out.append(
        "\n/// `buildEnchantmentList` outputs for a known seed: the item, the level\n"
        "/// and the seed, then the `(id, level)` pairs it picked in order and the\n"
        "/// `nextInt(1000)` that follows, which counts the draws it made.\n"
        "#[cfg(test)]\n"
        "pub const VECTORS: &[(&str, i32, i64, &[(u32, u32)], i32)] = &[\n"
    )
    for item, level, seed, listing, after in vectors:
        pairs = ", ".join(f"({i}, {l})" for i, l in listing)
        out.append(f"    (\"{item}\", {level}, {seed}, &[{pairs}], {after}),\n")
    out.append("];\n")
    args.out.write_text("".join(out))
    print(
        f"wrote {args.out}: {len(enchantments)} enchantments, "
        f"{len(items)} items, {len(vectors)} vectors"
    )


if __name__ == "__main__":
    main()
