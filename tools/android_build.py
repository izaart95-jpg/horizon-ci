#!/usr/bin/env python3
"""Build an optimized Rust APK with Android's stock NativeActivity and Rust system-IME adapter.

Requires Android SDK, NDK, Rust Android target, and a JDK (for APK signing).
Generated APKs and the throwaway signing key stay in .local/android.
"""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import zipfile
import json
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {'x86_64': 'x86_64-linux-android', 'arm64-v8a': 'aarch64-linux-android',
           'armeabi-v7a': 'armv7-linux-androideabi', 'x86': 'i686-linux-android'}
# Generated 1.8.9 item assets the client jar does not ship (see
# crates/horizon-client/examples/prepare_1_8_9_items.rs).
ITEM_MODEL_BASES = {'template_skull', 'template_banner', 'template_chest',
                    'spawn_egg_base', 'spawn_egg_overlay'}
ITEM_FRAME_NAME = re.compile(r'(?:clock|compass)_\d\d')
# The crafting recipes generated from the 1.8.9 RecipeDispatcher dump
# (crates/horizon-client/examples/prepare_1_8_9_recipes.rs).
GENERATED_RECIPE = re.compile(r'1_8_9_(?:\d{4}_)?[a-z0-9_]+\.json')
# The chest tables generated from the 1.8 jar's WeightedRandomChestContent
# lists (crates/horizon-items/src/chest_loot_1_8_9.rs), relative to
# data/minecraft/loot_table/chests/. The rest of data/ is still the 26.3 tree
# and stays out of public bundles.
CHEST_LOOT_1_8_9 = {
    'abandoned_mineshaft.json', 'desert_pyramid.json', 'jungle_temple.json',
    'jungle_temple_dispenser.json', 'nether_bridge.json', 'simple_dungeon.json',
    'spawn_bonus_chest.json', 'stronghold_corridor.json', 'stronghold_crossing.json',
    'stronghold_library.json', 'village/village_weaponsmith.json',
}
# The 1.8 painting motives generated by
# crates/horizon-client/examples/prepare_1_8_9_paintings.rs.
PAINTINGS_1_8_9 = {
    'alban.json', 'aztec.json', 'aztec2.json', 'bomb.json', 'burning_skull.json',
    'bust.json', 'courbet.json', 'creebet.json', 'donkey_kong.json', 'fighters.json',
    'graham.json', 'kebab.json', 'match.json', 'pigscene.json', 'plant.json',
    'pointer.json', 'pool.json', 'sea.json', 'skeleton.json', 'skull_and_roses.json',
    'stage.json', 'sunset.json', 'void.json', 'wanderer.json', 'wasteland.json',
    'wither.json',
}
# The textures the same generator crops out of the 1.8 atlas: one per motive
# plus the wooden back patch (`PaintingEntityRenderer`'s 0.75,0 x 0,1/16 UVs).
PAINTING_TEXTURES_1_8_9 = {name.replace('.json', '.png') for name in PAINTINGS_1_8_9} | {'back.png'}
# The 1.8 banner patterns generated by
# crates/horizon-client/examples/prepare_1_8_9_banners.rs: the enum's 39
# entries (no 26.3 flow/guster/globe/piglin) and its six item tags. 1.8 has
# no banner_pattern registry, so none of these come from the data pack.
BANNER_PATTERNS_1_8_9 = {
    'base', 'border', 'bricks', 'circle', 'creeper', 'cross', 'curly_border',
    'diagonal_left', 'diagonal_right', 'diagonal_up_left', 'diagonal_up_right',
    'flower', 'gradient', 'gradient_up', 'half_horizontal',
    'half_horizontal_bottom', 'half_vertical', 'half_vertical_right', 'mojang',
    'rhombus', 'skull', 'small_stripes', 'square_bottom_left',
    'square_bottom_right', 'square_top_left', 'square_top_right',
    'straight_cross', 'stripe_bottom', 'stripe_center', 'stripe_downleft',
    'stripe_downright', 'stripe_left', 'stripe_middle', 'stripe_right',
    'stripe_top', 'triangle_bottom', 'triangle_top', 'triangles_bottom',
    'triangles_top',
}
BANNER_TAGS_1_8_9 = {
    'no_item_required.json',
    'pattern_item/bordure_indented.json', 'pattern_item/creeper.json',
    'pattern_item/field_masoned.json', 'pattern_item/flower.json',
    'pattern_item/mojang.json', 'pattern_item/skull.json',
}
# The 1.8 masks converted to the current alpha form, plus the pole-and-cloth
# texture 1.8 names `entity/banner_base.png` copied to `entity/banner/banner_base`.
BANNER_TEXTURES_1_8_9 = (
    {name + '.png' for name in BANNER_PATTERNS_1_8_9} - {'base.png'}
) | {'banner_base.png'}


def latest(directory):
    return max(directory.iterdir(), key=lambda p: tuple(int(v) for v in p.name.split('.')))


def run(command, **kwargs):
    print(' '.join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), check=True, **kwargs)


def save_crash_symbols(library, stripped, abi, objcopy, revision):
    """Keep matching symbols locally; never enlarge or attach them to the APK."""
    digest = hashlib.sha256(stripped.read_bytes()).hexdigest()
    notes = subprocess.check_output([str(objcopy.with_name('llvm-readelf' + objcopy.suffix)), '--notes', str(stripped)], text=True)
    build_id = notes.split('Build ID:', 1)[1].split()[0] if 'Build ID:' in notes else None
    key = build_id or digest
    output = ROOT / '.local/android/native-symbols' / abi
    output.mkdir(parents=True, exist_ok=True)
    symbols = output / (key + '.debug')
    if not symbols.is_file():
        run([objcopy, '--only-keep-debug', library, symbols])
    (output / (key + '.json')).write_text(json.dumps({
        'schema': 1, 'abi': abi, 'source_commit': revision, 'build_id': build_id,
        'packaged_library_sha256': digest, 'symbols': symbols.name,
    }, indent=2) + '\n', encoding='utf-8')
    print(f'Private crash symbols: {symbols}', flush=True)


def generated_engine_file(name):
    path = Path(name)
    if len(path.parts) == 1:
        return name in {
            'attributes.json', 'block-behaviours.json', 'cached-collision.nbt',
            'command-registries.json', 'commands.json', 'creative-inventory.json',
            'damage-catalog.json', 'entity-models.json', 'entity-types.json',
            'facts.json', 'gameplay-facts.json', 'horizon-resources.json', 'items.json',
            'landing-definitions.json', 'mob-data.json', 'model-states.json',
            'movement-properties.nbt', 'occlusion.nbt', 'player-float-ids.json',
            'registries.json', 'render-definitions.json'}
    if path.parts[:3] == ('assets', 'minecraft', 'items') and len(path.parts) == 4:
        # ClientItem definitions exist only in the generated 1.8.9 root; the
        # 1.8 client jar predates the folder (see prepare_1_8_9_items).
        return path.suffix == '.json'
    if path.parts[:4] == ('assets', 'minecraft', 'models', 'item') and len(path.parts) == 5:
        return path.suffix == '.json' and (path.stem in ITEM_MODEL_BASES or ITEM_FRAME_NAME.fullmatch(path.stem) is not None)
    if path.parts[:4] == ('assets', 'minecraft', 'textures', 'items') and len(path.parts) == 5:
        return path.suffix == '.png' and ITEM_FRAME_NAME.fullmatch(path.stem) is not None
    # The 1.8 chest tables are generated from the 1.8 jar's hard-coded
    # WeightedRandomChestContent lists (horizon_items::chest_loot_1_8_9), not
    # copied from the 26.3 data pack, so a public bundle may carry exactly
    # these files. Every other loot table stays out until it is generated too.
    if path.parts[:4] == ('data', 'minecraft', 'loot_table', 'chests'):
        return '/'.join(path.parts[4:]) in CHEST_LOOT_1_8_9
    # The crafting recipes are generated from 1.8's own RecipeDispatcher, so a
    # public bundle may carry those files and no other recipe.
    if path.parts[:3] == ('data', 'minecraft', 'recipe') and len(path.parts) == 4:
        return path.suffix == '.json' and GENERATED_RECIPE.fullmatch(path.name) is not None
    # 1.8's 26 painting motives, generated from the jar's PaintingMotive enum;
    # 26.3's larger set has no 1.8 texture or save name.
    if path.parts[:3] == ('data', 'minecraft', 'painting_variant') and len(path.parts) == 4:
        return path.name in PAINTINGS_1_8_9
    if name == 'data/minecraft/tags/painting_variant/placeable.json':
        return True
    # The 26 motives' textures and the back patch, cropped from the 1.8 atlas;
    # the atlas itself is Mojang's and stays in the downloaded jar.
    if path.parts[:4] == ('assets', 'minecraft', 'textures', 'painting') and len(path.parts) == 5:
        return path.name in PAINTING_TEXTURES_1_8_9
    # 1.8's banner patterns are its enum, not the data pack's 43; the tags are
    # the six 1.8 ingredient items and the 32 layout patterns.
    if path.parts[:3] == ('data', 'minecraft', 'banner_pattern') and len(path.parts) == 4:
        return path.suffix == '.json' and path.stem in BANNER_PATTERNS_1_8_9
    if path.parts[:4] == ('data', 'minecraft', 'tags', 'banner_pattern'):
        return '/'.join(path.parts[4:]) in BANNER_TAGS_1_8_9
    # Converted pattern masks and the renamed pole-and-cloth texture; the 1.8
    # jar's own white-on-black masks and `entity/banner_base.png` stay out.
    if path.parts[:5] == ('assets', 'minecraft', 'textures', 'entity', 'banner') and len(path.parts) == 6:
        return path.name in BANNER_TEXTURES_1_8_9
    return (name in {'biome-parameters/nether.json', 'biome-parameters/overworld.json',
                    'worldgen/biome_parameters/nether.json', 'worldgen/biome_parameters/overworld.json'}
            or (path.parts[:2] == ('worldgen', 'blocks') and path.name in {
                'block-properties.nbt', 'cached-collision.nbt', 'cached-support.nbt',
                'survival-rules.json', 'survival-extra-definitions.json', 'placement-definitions.json',
                'structure-blocks.json'}
                and len(path.parts) == 3)
            or name == 'worldgen/block_flags.json')


def resources_version():
    """The folder `horizon_core::target::RESOURCES_VERSION` names.

    Follow the compile-time target switch (target.rs re-exports one version
    module) so the APK and the Rust build cannot disagree.
    """
    target = (ROOT / 'crates/horizon-core/src/target.rs').read_text(encoding='utf-8')
    module = re.search(r'pub use crate::(version_[A-Za-z0-9_]+) as current;', target)
    if module is None:
        raise ValueError('target.rs does not re-export a version module')
    source = (ROOT / 'crates/horizon-core/src' / f'{module.group(1)}.rs').read_text(encoding='utf-8')
    version = re.search(r'pub const VERSION_ID: &str = "([^"]+)";', source)
    if version is None:
        raise ValueError('target version module has no VERSION_ID')
    return version.group(1)


def engine_data(public=False):
    version = resources_version()
    resources = ROOT / '.local/horizon-client' / version
    if not (resources / 'horizon-resources.json').is_file():
        raise FileNotFoundError(f'Developer build needs prepared engine tables in {resources}; run the target version generator once')
    if public and not (resources / 'worldgen/blocks/structure-blocks.json').is_file():
        raise FileNotFoundError('Public build needs generated structure transforms; prepare the tables again')
    files = [p for p in resources.iterdir() if p.is_file() and p.suffix in ('.json', '.nbt') and p.name != 'asset-index.json']
    for name in ['worldgen', 'biome-parameters']:
        files.extend(p for p in (resources / name).rglob('*') if p.is_file())
    if version == '1.8.9':
        # A 1.8.9 client jar has no data/ (entity loot tables, advancements
        # and the dimension data are still 26.3-shaped) and the blockstate
        # overrides are generated, not in the jar, so the engine bundle
        # supplies both after the jar's own assets are unpacked. The chest
        # tables are generated from 1.8's own lists too (see CHEST_LOOT_1_8_9).
        files.extend(p for p in (resources / 'data').rglob('*') if p.is_file())
        files.extend(p for p in (resources / 'assets/minecraft/blockstates').rglob('*.json') if p.is_file())
        # The client jar also predates the per-item definitions, cropped
        # clock/compass frames and the special-rendered template models.
        # prepare_1_8_9_items lists every file it wrote, so the bundle follows
        # that list instead of guessing at names.
        manifest = resources / 'item-assets.json'
        if not manifest.is_file():
            raise FileNotFoundError(f'1.8.9 bundle needs generated item definitions in {manifest}; run prepare_1_8_9_items')
        item_assets = json.loads(manifest.read_text(encoding='utf-8'))['item_assets']
        for name in item_assets:
            path = resources / name
            if not path.is_file():
                raise FileNotFoundError(f'item-assets.json lists a missing file: {name}')
            files.append(path)
        # 1.8's paintings are crops of its single atlas; a public bundle may
        # carry those and not the atlas itself.
        painting_textures = resources / 'assets/minecraft/textures/painting'
        for name in sorted(PAINTING_TEXTURES_1_8_9):
            path = painting_textures / name
            if not path.is_file():
                raise FileNotFoundError(f'1.8.9 bundle needs the cropped painting texture {path}; run prepare_1_8_9_paintings')
            files.append(path)
        # 1.8's banner masks need the current alpha form and its pole-and-cloth
        # texture a new name; the bundle carries those conversions.
        banner_textures = resources / 'assets/minecraft/textures/entity/banner'
        for name in sorted(BANNER_TEXTURES_1_8_9):
            path = banner_textures / name
            if not path.is_file():
                raise FileNotFoundError(f'1.8.9 bundle needs the converted banner texture {path}; run prepare_1_8_9_banners')
            files.append(path)
    files.sort()
    if public:
        files = [p for p in files if generated_engine_file(p.relative_to(resources).as_posix())]
    fingerprint = hashlib.sha256(''.join(f'{p.relative_to(resources)}:{p.stat().st_size}:{p.stat().st_mtime_ns}\n' for p in files).encode()).hexdigest()
    output = ROOT / '.local/android' / ('engine-data-generated.zip' if public else 'engine-data.zip')
    stamp = output.with_suffix('.fingerprint')
    if not output.exists() or not stamp.exists() or stamp.read_text() != fingerprint:
        output.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(output.with_suffix('.partial'), 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=1) as archive:
            for file in files:
                archive.write(file, file.relative_to(resources).as_posix())
        output.with_suffix('.partial').replace(output)
        stamp.write_text(fingerprint)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--abi', choices=TARGETS, default='arm64-v8a')
    parser.add_argument('--sdk', type=Path, default=os.environ.get('ANDROID_HOME') or Path(os.environ.get('LOCALAPPDATA', str(Path.home()))) / 'Android/Sdk')
    parser.add_argument('--java-home', type=Path, default=os.environ.get('JAVA_HOME') or 'C:/Program Files/Android/Android Studio/jbr')
    parser.add_argument('--ndk-version', help='Select an installed NDK version explicitly (CI reproducibility)')
    parser.add_argument('--build-tools-version', help='Select an installed Android build-tools version explicitly')
    parser.add_argument('--skip-rust', action='store_true')
    parser.add_argument('--rust-only', action='store_true', help='Build the Rust host without touching shared APK staging')
    parser.add_argument('--release-candidate', action='store_true', help='Build a non-debuggable candidate and audit privacy; this does not authorize redistribution of bundled game resources')
    parser.add_argument('--public', action='store_true', help='Distribution APK: generated tables only; original resources download from Mojang')
    parser.add_argument('--dev-build', help='Public, non-debuggable dev channel label (separate .dev package)')
    parser.add_argument('--dev-version-code', type=int, help='Monotonically increasing dev channel version code')
    parser.add_argument('--profile', choices=['release', 'fast', 'dev'], help='Public/candidate builds default to release (ThinLTO); local builds default to optimized fast')
    parser.add_argument('--gradle', type=Path, help='Gradle 8.14 executable (otherwise discover the cached distribution)')
    parser.add_argument('--check', action='store_true', help='Only type-check the Android target')
    parser.add_argument('--clippy', action='store_true', help='Run Android Clippy with warnings denied')
    parser.add_argument('--bootstrap', type=Path, help=argparse.SUPPRESS)  # Old scripts: no longer used.
    args = parser.parse_args()
    if args.dev_build is not None:
        if not args.public or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9.-]{0,63}', args.dev_build):
            parser.error('--dev-build requires --public and a short alphanumeric/dot/dash label')
        if args.dev_version_code is None or not 1 <= args.dev_version_code <= 2100000000:
            parser.error('--dev-build requires --dev-version-code in 1..2100000000')
    elif args.dev_version_code is not None:
        parser.error('--dev-version-code requires --dev-build')
    if args.profile is None:
        args.profile = 'release' if args.public or args.release_candidate else 'fast'
    if args.public:
        args.release_candidate = True
        if args.skip_rust:
            parser.error('--public cannot reuse a native library from a different build mode')
    if args.release_candidate and args.profile == 'dev':
        parser.error('--release-candidate requires an optimized release or fast profile')
    suffix = '.exe' if os.name == 'nt' else ''
    for name, value in [('ndk-version', args.ndk_version), ('build-tools-version', args.build_tools_version)]:
        if value is not None and not re.fullmatch(r'\d+(?:\.\d+)+', value):
            parser.error(f'--{name} must be a numeric SDK version')
    tools = args.sdk / 'build-tools' / args.build_tools_version if args.build_tools_version else latest(args.sdk / 'build-tools')
    ndk_root = args.sdk / 'ndk' / args.ndk_version if args.ndk_version else latest(args.sdk / 'ndk')
    if not tools.is_dir() or not ndk_root.is_dir():
        raise FileNotFoundError('Requested Android build-tools or NDK version is not installed')
    ndk = ndk_root / 'toolchains/llvm/prebuilt' / ('windows-x86_64' if os.name == 'nt' else 'linux-x86_64')
    target = TARGETS[args.abi]
    # NDK spells the ARMv7 compiler triple differently from Rust. Android 8.1
    # is the legacy build's floor; the modern builds keep their existing floor.
    compiler_target = 'armv7a-linux-androideabi' if args.abi == 'armeabi-v7a' else target
    legacy = args.abi in ('armeabi-v7a', 'x86')
    min_sdk = 27 if legacy else 28
    features = ['--no-default-features', '--features', 'audio'] if legacy else []
    manifests = [(['-p', 'horizon-android'], features)]
    environment = dict(os.environ)
    environment['PATH'] = os.pathsep.join([str(ndk / 'bin'), str(args.java_home / 'bin'), environment['PATH']])
    environment['JAVA_HOME'] = str(args.java_home)
    target_dir = Path(environment.get('CARGO_TARGET_DIR', ROOT / 'target')).resolve()
    environment['CARGO_TARGET_DIR'] = str(target_dir)
    triple = target.replace('-', '_')
    clang = ndk / 'bin' / (compiler_target + str(min_sdk) + '-clang' + ('.cmd' if os.name == 'nt' else ''))
    environment[f'CC_{triple}'] = str(clang)
    environment[f'CXX_{triple}'] = str(ndk / 'bin' / (compiler_target + str(min_sdk) + '-clang++' + ('.cmd' if os.name == 'nt' else '')))
    environment[f'AR_{triple}'] = str(ndk / 'bin' / ('llvm-ar' + suffix))
    environment[f'CARGO_TARGET_{triple.upper()}_LINKER'] = str(clang)
    environment['CARGO_PROFILE_DEV_DEBUG'] = '0'
    environment['HORIZON_ANDROID_PUBLIC'] = '1' if args.public else '0'
    try:
        environment['HORIZON_ANDROID_BUILD_COMMIT'] = subprocess.check_output(
            ['git', 'rev-parse', '--short=12', 'HEAD'], cwd=ROOT,
            stderr=subprocess.DEVNULL, text=True).strip()
        environment['HORIZON_ANDROID_BUILD_DIRTY'] = str(bool(subprocess.check_output(
            ['git', 'status', '--porcelain', '--untracked-files=no'], cwd=ROOT,
            stderr=subprocess.DEVNULL, text=True).strip())).lower()
    except (OSError, subprocess.CalledProcessError):
        environment['HORIZON_ANDROID_BUILD_COMMIT'] = 'source-export'
        environment['HORIZON_ANDROID_BUILD_DIRTY'] = 'unknown'
    if args.release_candidate:
        flags = environment.get('CARGO_ENCODED_RUSTFLAGS', '').split('\x1f') if environment.get('CARGO_ENCODED_RUSTFLAGS') else environment.get('RUSTFLAGS', '').split()
        for original, replacement in [(Path.home(), '/build'), (ROOT, '/horizon')]:
            for prefix in dict.fromkeys([str(original), original.as_posix()]):
                flags.append(f'--remap-path-prefix={prefix}={replacement}')
        environment['CARGO_ENCODED_RUSTFLAGS'] = '\x1f'.join(flags)
    if args.check or args.clippy:
        for selection, host_features in manifests:
            command = ['cargo', 'clippy' if args.clippy else 'check', *selection, '--target', target, *host_features]
            if args.clippy:
                command += ['--no-deps', '--', '-D', 'warnings']
            run(command, cwd=ROOT, env=environment)
        return
    if not args.skip_rust:
        for selection, host_features in manifests:
            run(['cargo', 'build', *selection, '--target', target, '--profile', args.profile, *host_features], cwd=ROOT, env=environment)
    if args.rust_only:
        return
    output = ROOT / '.local/android/apk' / args.abi
    output.mkdir(parents=True, exist_ok=True)
    staging = ROOT / '.local/android/gradle-jni' / args.abi
    staging.mkdir(parents=True, exist_ok=True)
    (staging / 'libhorizon_android_native.so').unlink(missing_ok=True)
    for name in ('libhorizon_android.so',):
        library = target_dir / target / ('debug' if args.profile == 'dev' else args.profile) / name
        if not library.is_file():
            raise FileNotFoundError(library)
        shutil.copyfile(library, staging / name)
        run([ndk / 'bin' / ('llvm-strip' + suffix), '--strip-unneeded', staging / name])
        if args.profile == 'release':
            save_crash_symbols(library, staging / name, args.abi,
                               ndk / 'bin' / ('llvm-objcopy' + suffix),
                               environment.get('HORIZON_ANDROID_BUILD_COMMIT', 'unknown'))
    assets = ROOT / '.local/android/gradle-assets'
    assets.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / 'LICENSE', assets / 'LICENSE.txt')
    shutil.copyfile(ROOT / 'THIRD_PARTY_NOTICES.md', assets / 'THIRD_PARTY_NOTICES.md')
    shutil.copyfile(engine_data(args.public), assets / 'engine-data.zip')
    controls = ROOT / '.local/android/bedrock-controls.zip'
    if not args.public and not controls.is_file():
        import sys
        run([sys.executable, ROOT / 'tools/android_bedrock_controls.py'], cwd=ROOT)
    if args.public:
        (assets / 'bedrock-controls.zip').unlink(missing_ok=True)
    else:
        shutil.copyfile(controls, assets / 'bedrock-controls.zip')
    key = ROOT / '.local/android/debug.keystore'
    if not key.exists():
        run([args.java_home / 'bin' / ('keytool' + suffix), '-genkeypair', '-keystore', key, '-storepass', 'android', '-keypass', 'android', '-alias', 'androiddebugkey', '-keyalg', 'RSA', '-validity', '3650', '-dname', 'CN=Horizon Android Development'])
    gradle = args.gradle
    if gradle is None:
        candidates = list((Path.home() / '.gradle/wrapper/dists/gradle-8.14-all').glob('*/gradle-8.14/bin/gradle' + ('.bat' if os.name == 'nt' else '')))
        if not candidates:
            raise FileNotFoundError('Install Gradle 8.14 or pass --gradle PATH')
        gradle = candidates[0]
    environment['ANDROID_HOME'] = str(args.sdk)
    variant = 'release' if args.release_candidate else 'debug'
    dev_properties = (['-PappId=dev.horizon.android.dev', '-PdevBuild=' + args.dev_build,
                       '-PdevVersionCode=' + str(args.dev_version_code)] if args.dev_build else [])
    run([gradle, '--no-daemon', '-p', ROOT / 'packaging/android', '-Pabi=' + args.abi, '-PminSdk=' + str(min_sdk), *dev_properties, 'assemble' + variant.title()], cwd=ROOT, env=environment)
    apk = output / ('horizon-android-public.apk' if args.public else 'horizon-android-release.apk' if args.release_candidate else 'horizon-android.apk')
    shutil.copyfile(ROOT / f'.local/android/gradle-build/outputs/apk/{variant}/HorizonAndroid-{variant}.apk', apk)
    # Invoke the signing JAR directly so Windows does not need a batch-file shell.
    signer = [args.java_home / 'bin' / ('java' + suffix), '-jar', tools / 'lib/apksigner.jar']
    run([*signer, 'verify', '--verbose', apk])
    if args.release_candidate:
        import sys
        run([sys.executable, ROOT / 'tools/check_android_release.py', apk, '--aapt2', tools / ('aapt2' + suffix), *(['--public'] if args.public else []), *(['--app-id', 'dev.horizon.android.dev'] if args.dev_build else [])], cwd=ROOT)
    print(f'APK: {apk}', flush=True)


